"""Mutants of the lines changed on 2026-10-13 for README sentence 9 (mixed-order keys and R, 9d4cf2c), run against
the whole suite: each mutant is applied to a copy of this directory, and is killed iff at least one of
test_piccolo_ordine.py, test_generativi.py, test_nemesis.py, test_ed25519.py, test_frase5.py exits non-zero, or
the 50 vectors at 9d4cf2c do not give exactly 49/50 with acc-complete-not-boolean the one disagreement. The
unmutated copy must pass every one of them first (the bench must be able to pass).

One mutant is expected to survive and is listed apart: with the A check in place, the R check of verify() cannot
change its result. If A is in the subgroup generated by B and the cofactorless equation holds, then
R = [S]B - [k]A is in that subgroup too, so a mixed-order R always fails the equation. It is kept because
sentence 9 names R, and so that the R refusal does not depend on which equation is used.

python3 mutanti_v3.py   -> exit 0 iff the unmutated copy passes, every mutant not listed as equivalent is
                           killed, and the one listed as equivalent survives
"""
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS = ["test_piccolo_ordine.py", "test_generativi.py", "test_nemesis.py", "test_ed25519.py", "test_frase5.py"]
ED, AC = "ed25519_rfc8032.py", "acceptance_check.py"
CHECK9 = "    if not _prime_order(A) or not _prime_order(R):                  # README sentence 9 (not RFC 8032)\n"

MUTANTS = [
    ("ed: no mixed-order check in verify", ED, CHECK9, "    if False:\n"),
    ("ed: mixed-order A allowed in verify", ED, CHECK9, "    if not _prime_order(R):\n"),
    ("ed: [L]P replaced by [8L]P (every point passes)", ED, "_scalar_mul(L, P)", "_scalar_mul(8 * L, P)"),
    ("ed: [L]P replaced by [4L]P (torsion of order 2, 4 passes)", ED, "_scalar_mul(L, P)", "_scalar_mul(4 * L, P)"),
    ("ed: [L]P replaced by [2L]P", ED, "_scalar_mul(L, P)", "_scalar_mul(2 * L, P)"),
    ("ed: prime-order test negated", ED, "    return _encode_point(_scalar_mul(L, P)) == _encode_point(_NEUTRAL)",
     "    return _encode_point(_scalar_mul(L, P)) != _encode_point(_NEUTRAL)"),
    ("ed: key_problem ignores mixed order", ED, '        return "mixed-order point"', "        return None"),
    ("ed: key_problem tests mixed order before small order", ED,
     '    if _small_order(A):\n        return "small-order point"\n    if not _prime_order(A):\n        return "mixed-order point"\n',
     '    if not _prime_order(A):\n        return "mixed-order point"\n    if _small_order(A):\n        return "small-order point"\n'),
    ("ac: mixed-order key kept as a key", AC, 'if problem in ("small-order point", "mixed-order point"):',
     'if problem == "small-order point":'),
    ("ac: mixed-order key -> input_error", AC, 'if problem in ("small-order point", "mixed-order point"):',
     'if problem == "mixed-order point":\n                raise InputError("mixed")\n            if problem == "small-order point":'),
]
EQUIVALENT = [
    ("ed: mixed-order R allowed in verify (equivalent, see docstring)", ED, CHECK9, "    if not _prime_order(A):\n"),
]


def run_suite(d):
    failed = []
    env = dict(os.environ, HOME=d)
    for t in TESTS:
        p = subprocess.run([sys.executable, "-B", t], cwd=d, capture_output=True, timeout=1800, env=env)
        if p.returncode != 0:
            failed.append(t)
    p = subprocess.run([sys.executable, "-B", "misura_vettori.py", os.path.join("fonti", "9d4cf2c_vectors.json")],
                       cwd=d, capture_output=True, timeout=600, env=env)
    dis = [ln.split()[0] for ln in p.stdout.decode(errors="replace").splitlines() if " DISAGREE " in ln]
    if b"TOTAL 49/50 agree" not in p.stdout or dis != ["acc-complete-not-boolean"]:
        failed.append("vectors")
    return failed


def copy_tree(dst):
    for n in os.listdir(HERE):
        if n.endswith(".py") or n == "fonti":
            s = os.path.join(HERE, n)
            (shutil.copytree if os.path.isdir(s) else shutil.copy2)(s, os.path.join(dst, n))


def main():
    with tempfile.TemporaryDirectory() as td:
        base = os.path.join(td, "base")
        os.mkdir(base)
        copy_tree(base)
        f = run_suite(base)
        print("unmutated copy: %s" % ("passes" if not f else "FAILS %s (bench broken)" % f), flush=True)
        if f:
            return 1
        bad = []
        for i, (name, fn, old, new) in enumerate(MUTANTS + EQUIVALENT):
            d = os.path.join(td, "m%d" % i)
            os.mkdir(d)
            copy_tree(d)
            src = open(os.path.join(d, fn)).read()
            if src.count(old) != 1:
                print("%-62s anchor found %d times" % (name, src.count(old)), flush=True)
                bad.append(name)
                continue
            open(os.path.join(d, fn), "w").write(src.replace(old, new))
            f = run_suite(d)
            print("%-62s %s %s" % (name, "killed by" if f else "SURVIVED", f), flush=True)
            if bool(f) == (i >= len(MUTANTS)):
                bad.append(name)
            shutil.rmtree(d)
        print("MUTANTS %d (+%d equivalent), NOT AS EXPECTED %s" % (len(MUTANTS), len(EQUIVALENT), bad))
        return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
